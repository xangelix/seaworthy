//! The Group Policy template for a product's update policy and update
//! server: an ADMX file
//! (the policy definition) and its en-US ADML (the strings), for
//! `%SystemRoot%\PolicyDefinitions` or a domain's Central Store, and for
//! Intune's ADMX ingestion.
//!
//! One policy, `UpdatePolicy`, a machine-wide enum written as `REG_SZ` to
//! `HKLM\SOFTWARE\Policies\<Vendor>\<Product>\UpdatePolicy`. Its values are
//! `auto`, `notify` and `off` ([`crate::config::UpdatePolicy`]). The helper
//! reads that key first. The MSI's `UPDATES=` default lives outside
//! `Policies`, so Group Policy always wins.
//!
//! Each product gets its own namespace (`<Vendor>.Policies.<Product>`) and
//! its own top-level category, so two products' templates (or two
//! repositories from one vendor) never collide in the Central Store. The
//! prefix and category name are the vendor and product with `.` and `-`
//! removed, and an `_` in front when that would start with a digit
//! (`3M` → `_3MAgent`): the schema's names start with a letter or `_`.
//!
//! Disabled and Not Configured both leave the value unset, so the
//! installation's default applies; the help text says so, because an
//! administrator might read "Disabled" as "updates off". `off` is an
//! explicit choice in the list.
//!
//! A second policy, `Server`, names the machine's update server:
//! an `https://` URL written as `REG_SZ` to the same key's `Server`, which
//! the helper reads before the MSI's `SERVER=`
//! (`seaworthy_updater::read_admin_server`) and checks itself. Not Configured
//! leaves the installation's server, else the product's default.

/// An ADMX/ADML pair.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Template {
    /// The file stem both files share (`Acme.Collector`).
    pub stem: String,
    /// The ADMX text.
    pub admx: String,
    /// The en-US ADML text.
    pub adml: String,
}

fn xml(text: &str) -> String {
    text.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
        .replace('\'', "&apos;")
}

/// The template for one product. `vendor` and `product` are validated
/// directory names (`[A-Za-z0-9][A-Za-z0-9._-]*`), so they are valid in
/// registry keys and policy names. `display_name` is any plain text.
#[must_use]
pub fn template(vendor: &str, product: &str, display_name: &str) -> Template {
    let mut id = format!(
        "{}{}",
        vendor.replace(['.', '-'], ""),
        product.replace(['.', '-'], "")
    );
    if !id.starts_with(|c: char| c.is_ascii_alphabetic() || c == '_') {
        id.insert(0, '_');
    }
    let namespace = format!("{vendor}.Policies.{product}");
    let key = format!("SOFTWARE\\Policies\\{vendor}\\{product}");
    let admx = format!(
        r#"<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by seaworthy: a product's update policy. -->
<policyDefinitions xmlns:xsd="http://www.w3.org/2001/XMLSchema" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" revision="1.0" schemaVersion="1.0" xmlns="http://schemas.microsoft.com/GroupPolicy/2006/07/PolicyDefinitions">
  <policyNamespaces>
    <target prefix="{id}" namespace="{namespace}" />
    <using prefix="windows" namespace="Microsoft.Policies.Windows" />
  </policyNamespaces>
  <resources minRequiredRevision="1.0" />
  <categories>
    <category name="{id}" displayName="$(string.Category)" />
  </categories>
  <policies>
    <policy name="UpdatePolicy" class="Machine" displayName="$(string.UpdatePolicy)" explainText="$(string.UpdatePolicy_Help)" presentation="$(presentation.UpdatePolicy)" key="{key}">
      <parentCategory ref="{id}" />
      <supportedOn ref="windows:SUPPORTED_Windows_10_0" />
      <elements>
        <enum id="UpdatePolicy" valueName="UpdatePolicy" required="true">
          <item displayName="$(string.UpdatePolicy_auto)"><value><string>auto</string></value></item>
          <item displayName="$(string.UpdatePolicy_notify)"><value><string>notify</string></value></item>
          <item displayName="$(string.UpdatePolicy_off)"><value><string>off</string></value></item>
        </enum>
      </elements>
    </policy>
    <policy name="Server" class="Machine" displayName="$(string.Server)" explainText="$(string.Server_Help)" presentation="$(presentation.Server)" key="{key}">
      <parentCategory ref="{id}" />
      <supportedOn ref="windows:SUPPORTED_Windows_10_0" />
      <elements>
        <text id="Server" valueName="Server" required="true" maxLength="2048" />
      </elements>
    </policy>
  </policies>
</policyDefinitions>
"#,
        id = xml(&id),
        namespace = xml(&namespace),
        key = xml(&key),
    );
    let adml = format!(
        r#"<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by seaworthy. -->
<policyDefinitionResources xmlns:xsd="http://www.w3.org/2001/XMLSchema" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" revision="1.0" schemaVersion="1.0" xmlns="http://schemas.microsoft.com/GroupPolicy/2006/07/PolicyDefinitions">
  <displayName>{display}</displayName>
  <description>The update policy of {display}.</description>
  <resources>
    <stringTable>
      <string id="Category">{display}</string>
      <string id="UpdatePolicy">Update policy</string>
      <string id="UpdatePolicy_Help">How {display} installs new releases when its server requires one.

Automatic: the update helper downloads the release the server names, verifies its signatures, and installs it with Windows Installer. This is the default.

Notify only: the product logs the required version and keeps retrying the connection. An administrator installs the release.

Off: like Notify only. Use it where server and clients are upgraded together.

A value set here overrides the default chosen at installation (UPDATES=). Disabled and Not Configured leave the installation's default in effect; choose Off to turn updates off.</string>
      <string id="UpdatePolicy_auto">Automatic (install signed releases)</string>
      <string id="UpdatePolicy_notify">Notify only (log the required version)</string>
      <string id="UpdatePolicy_off">Off</string>
      <string id="Server">Update server</string>
      <string id="Server_Help">The server whose release {display}'s update helper installs on this machine: an https:// URL with a host, and optionally a port and a path (no user name, query or fragment).

A value set here overrides the server chosen at installation (SERVER=). Not Configured and Disabled leave the installation's server in effect, else the product's default.

A user whose copy of {display} connects to another server can still connect, but updates for that user are Notify only: an individual's server never drives a machine-wide install.

The update helper refuses a value that isn't such a URL, and installs nothing until it's corrected.</string>
    </stringTable>
    <presentationTable>
      <presentation id="UpdatePolicy">
        <dropdownList refId="UpdatePolicy" noSort="true" defaultItem="0">Update policy:</dropdownList>
      </presentation>
      <presentation id="Server">
        <textBox refId="Server">
          <label>Update server URL:</label>
        </textBox>
      </presentation>
    </presentationTable>
  </resources>
</policyDefinitionResources>
"#,
        display = xml(display_name),
    );
    Template {
        stem: format!("{vendor}.{product}"),
        admx,
        adml,
    }
}
